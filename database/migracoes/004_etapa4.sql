-- Defesa em profundidade: cliente bloqueado não ocupa agenda; falta/atraso (FALTOU) bloqueia o cliente.
CREATE OR REPLACE FUNCTION fn_regras_cliente_agendamento() RETURNS trigger LANGUAGE plpgsql AS $f$
BEGIN
  IF NEW.status = 'FALTOU' AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM 'FALTOU') THEN
    UPDATE clientes SET bloqueado = TRUE, bloqueado_em = CURRENT_TIMESTAMP,
      bloqueio_motivo = 'Falta ou atraso superior a 30 minutos (agendamento ' || NEW.id || ')'
    WHERE id = NEW.cliente_id AND NOT bloqueado;
  ELSIF NEW.status IN ('SOLICITADO','CONFIRMADO') AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM NEW.status)
        AND EXISTS (SELECT 1 FROM clientes c WHERE c.id = NEW.cliente_id AND c.bloqueado) THEN
    RAISE EXCEPTION 'Cadastro bloqueado: procure a barbearia para liberar.' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END $f$;
DROP TRIGGER IF EXISTS tg_regras_cliente_agendamento ON agendamentos;
CREATE TRIGGER tg_regras_cliente_agendamento BEFORE INSERT OR UPDATE OF status ON agendamentos
  FOR EACH ROW EXECUTE FUNCTION fn_regras_cliente_agendamento();

