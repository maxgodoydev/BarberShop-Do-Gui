-- Execução (após schema.sql): psql -v ON_ERROR_STOP=1 -d barbershop_gui -f database/migracoes/004_etapa4.sql
-- Modelo: agendamentos.servico_id continua sendo o serviço principal (compatível com as consultas atuais);
--         agendamento_servicos guarda TODOS os serviços; duracao_minutos/preco_referencia = totais.
-- Fluxo: RESERVA_TEMPORARIA -> SOLICITADO (aguarda o link no e-mail; ocupa agenda) -> CONFIRMADO (cliente clicou) | EXPIRADO.
BEGIN;
ALTER TABLE clientes ADD COLUMN IF NOT EXISTS bloqueado BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE clientes ADD COLUMN IF NOT EXISTS bloqueado_em TIMESTAMP;
ALTER TABLE clientes ADD COLUMN IF NOT EXISTS bloqueio_motivo VARCHAR(200);
ALTER TABLE agendamentos ADD COLUMN IF NOT EXISTS confirmado_via_link_em TIMESTAMP;
ALTER TABLE agendamentos DROP CONSTRAINT IF EXISTS ck_agendamento_status;
ALTER TABLE agendamentos ADD CONSTRAINT ck_agendamento_status CHECK (status IN
  ('RESERVA_TEMPORARIA','SOLICITADO','CONFIRMADO','CONCLUIDO','CANCELADO','EXPIRADO','FALTOU'));
ALTER TABLE tokens_acesso ADD COLUMN IF NOT EXISTS finalidade VARCHAR(12) NOT NULL DEFAULT 'CONSULTA';
ALTER TABLE tokens_acesso ADD COLUMN IF NOT EXISTS agendamento_id BIGINT REFERENCES agendamentos(id) ON DELETE CASCADE;
ALTER TABLE tokens_acesso DROP CONSTRAINT IF EXISTS ck_token_finalidade;
ALTER TABLE tokens_acesso ADD CONSTRAINT ck_token_finalidade CHECK (finalidade IN ('CONSULTA','CONFIRMACAO')
  AND (finalidade = 'CONSULTA' OR agendamento_id IS NOT NULL));

CREATE TABLE IF NOT EXISTS agendamento_servicos (
  agendamento_id  BIGINT NOT NULL REFERENCES agendamentos(id) ON DELETE CASCADE,
  servico_id      BIGINT NOT NULL REFERENCES servicos(id),
  ordem           SMALLINT NOT NULL DEFAULT 1,
  preco           NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
  duracao_minutos INTEGER NOT NULL CHECK (duracao_minutos > 0),
  PRIMARY KEY (agendamento_id, servico_id)
);
INSERT INTO agendamento_servicos (agendamento_id, servico_id, preco, duracao_minutos)
  SELECT a.id, a.servico_id, a.preco_referencia, a.duracao_minutos FROM agendamentos a
  WHERE NOT EXISTS (SELECT 1 FROM agendamento_servicos x WHERE x.agendamento_id = a.id);

CREATE TABLE IF NOT EXISTS produtos (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        VARCHAR(100) NOT NULL UNIQUE,
  marca       VARCHAR(60) NOT NULL,
  preco       NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
  estoque     INTEGER NOT NULL DEFAULT 0 CHECK (estoque >= 0),
  ativo       BOOLEAN NOT NULL DEFAULT TRUE,
  ilustrativo BOOLEAN NOT NULL DEFAULT TRUE   -- preço estimado até validação do proprietário
);
CREATE TABLE IF NOT EXISTS agendamento_produtos (
  agendamento_id  BIGINT NOT NULL REFERENCES agendamentos(id) ON DELETE CASCADE,
  produto_id      BIGINT NOT NULL REFERENCES produtos(id),
  quantidade      SMALLINT NOT NULL DEFAULT 1 CHECK (quantidade BETWEEN 1 AND 5),
  preco_unitario  NUMERIC(10,2) NOT NULL CHECK (preco_unitario >= 0),
  PRIMARY KEY (agendamento_id, produto_id)
);
