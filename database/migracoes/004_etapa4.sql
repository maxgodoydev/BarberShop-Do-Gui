-- Combinações proibidas na mesma visita (simétricas). Combo exclui seus componentes; cortes se excluem entre si.
CREATE TABLE IF NOT EXISTS servico_exclusoes (
  servico_id BIGINT NOT NULL REFERENCES servicos(id) ON DELETE CASCADE,
  exclui_id  BIGINT NOT NULL REFERENCES servicos(id) ON DELETE CASCADE,
  PRIMARY KEY (servico_id, exclui_id), CHECK (servico_id <> exclui_id)
);
INSERT INTO servico_exclusoes (servico_id, exclui_id)
  SELECT a.id, b.id FROM servicos a JOIN servicos b ON a.id <> b.id
  WHERE (a.nome = 'Cabelo e barba' AND b.nome IN ('Corte tradicional','Degradê','Corte na máquina','Corte infantil','Barba'))
     OR (b.nome = 'Cabelo e barba' AND a.nome IN ('Corte tradicional','Degradê','Corte na máquina','Corte infantil','Barba'))
     OR (a.nome IN ('Corte tradicional','Degradê','Corte na máquina','Corte infantil') AND b.nome IN ('Corte tradicional','Degradê','Corte na máquina','Corte infantil'))
     OR (a.nome = 'Corte infantil' AND b.nome = 'Barba')
     OR (a.nome = 'Barba' AND b.nome = 'Corte infantil')
ON CONFLICT DO NOTHING;
