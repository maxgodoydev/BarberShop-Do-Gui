-- =====================================================================
-- BarberShop do Gui | Esquema PostgreSQL 15+ (idempotente)
-- Execução: psql -v ON_ERROR_STOP=1 -f database/schema.sql
-- Fuso: todos os TIMESTAMP são "hora local da barbearia" (America/Sao_Paulo),
-- sem fuso embutido. Detalhes em docs/modelo-de-dados.md.
-- =====================================================================
BEGIN;
CREATE EXTENSION IF NOT EXISTS btree_gist;  -- necessário para a restrição de exclusão

CREATE TABLE IF NOT EXISTS servicos (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome             VARCHAR(100) NOT NULL UNIQUE,
  descricao        VARCHAR(240) NOT NULL,
  preco            NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
  duracao_minutos  INTEGER NOT NULL CHECK (duracao_minutos BETWEEN 5 AND 480),
  requer_avaliacao BOOLEAN NOT NULL DEFAULT FALSE,   -- ex.: procedimentos químicos
  ilustrativo      BOOLEAN NOT NULL DEFAULT TRUE,    -- preço/duração ainda não validados
  ativo            BOOLEAN NOT NULL DEFAULT TRUE,
  ordem            INTEGER NOT NULL DEFAULT 100,
  criado_em        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS profissionais (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        VARCHAR(100) NOT NULL,
  ativo       BOOLEAN NOT NULL DEFAULT TRUE,
  ordem       INTEGER NOT NULL DEFAULT 100,
  criado_em   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_profissional_nome CHECK (length(trim(nome)) > 0)
);

CREATE TABLE IF NOT EXISTS profissional_servicos (
  profissional_id BIGINT NOT NULL REFERENCES profissionais(id) ON DELETE CASCADE,
  servico_id      BIGINT NOT NULL REFERENCES servicos(id) ON DELETE CASCADE,
  PRIMARY KEY (profissional_id, servico_id)
);

-- Janelas de trabalho. Uma pausa é representada por duas janelas no mesmo dia
-- (ex.: 09:00-12:00 e 13:00-19:00). dia_semana segue ISO: 1 = segunda ... 7 = domingo.
CREATE TABLE IF NOT EXISTS horarios_atendimento (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profissional_id BIGINT NOT NULL REFERENCES profissionais(id) ON DELETE CASCADE,
  dia_semana      SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
  hora_inicio     TIME NOT NULL,
  hora_fim        TIME NOT NULL,
  CONSTRAINT ck_horario_ordem CHECK (hora_fim > hora_inicio)
);
CREATE INDEX IF NOT EXISTS idx_horarios_prof_dia ON horarios_atendimento(profissional_id, dia_semana);

-- Bloqueios (férias, folga, imprevistos). profissional_id NULL = barbearia inteira.
CREATE TABLE IF NOT EXISTS bloqueios (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profissional_id BIGINT REFERENCES profissionais(id) ON DELETE CASCADE,
  inicio          TIMESTAMP NOT NULL,
  fim             TIMESTAMP NOT NULL,
  motivo          VARCHAR(200),
  criado_em       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_bloqueio_ordem CHECK (fim > inicio)
);
CREATE INDEX IF NOT EXISTS idx_bloqueios_periodo ON bloqueios(inicio, fim);

-- Dados mínimos do cliente. Sem senha: o acesso é por link de uso único enviado ao e-mail.
CREATE TABLE IF NOT EXISTS clientes (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome         VARCHAR(100) NOT NULL,
  email        VARCHAR(160) NOT NULL,
  telefone     VARCHAR(30),
  criado_em    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_cliente_nome CHECK (length(trim(nome)) > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_clientes_email ON clientes (lower(email));

CREATE TABLE IF NOT EXISTS agendamentos (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id       BIGINT REFERENCES clientes(id) ON DELETE RESTRICT,
  servico_id       BIGINT NOT NULL REFERENCES servicos(id) ON DELETE RESTRICT,
  profissional_id  BIGINT NOT NULL REFERENCES profissionais(id) ON DELETE RESTRICT,
  inicio           TIMESTAMP NOT NULL,
  fim              TIMESTAMP NOT NULL,
  duracao_minutos  INTEGER NOT NULL CHECK (duracao_minutos > 0),   -- cópia da duração na data do pedido
  preco_referencia NUMERIC(10,2) NOT NULL CHECK (preco_referencia >= 0), -- preço de tabela na data; NÃO é pagamento
  status           VARCHAR(20) NOT NULL DEFAULT 'SOLICITADO',
  observacao       VARCHAR(500),
  reserva_token_hash CHAR(64),               -- SHA-256 do token da reserva temporária
  expira_em        TIMESTAMP,                -- só para RESERVA_TEMPORARIA
  cancelado_por    VARCHAR(10),              -- CLIENTE | EQUIPE
  criado_em        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_agendamento_status CHECK (status IN
    ('RESERVA_TEMPORARIA','SOLICITADO','CONFIRMADO','CONCLUIDO','CANCELADO','EXPIRADO')),
  CONSTRAINT ck_agendamento_periodo CHECK (fim > inicio),
  CONSTRAINT ck_agendamento_cliente CHECK (status IN ('RESERVA_TEMPORARIA','EXPIRADO') OR cliente_id IS NOT NULL),
  CONSTRAINT ck_agendamento_cancelador CHECK (cancelado_por IS NULL OR cancelado_por IN ('CLIENTE','EQUIPE')),
  -- Garantia de integridade no banco: o mesmo profissional nunca tem dois intervalos
  -- ativos que se sobreponham (inclusive quando um serviço termina depois do início de outro).
  CONSTRAINT ex_agendamento_sem_sobreposicao EXCLUDE USING gist
    (profissional_id WITH =, tsrange(inicio, fim, '[)') WITH &&)
    WHERE (status IN ('RESERVA_TEMPORARIA','SOLICITADO','CONFIRMADO','CONCLUIDO'))
);
CREATE INDEX IF NOT EXISTS idx_agendamentos_inicio ON agendamentos(inicio);
CREATE INDEX IF NOT EXISTS idx_agendamentos_status_inicio ON agendamentos(status, inicio);
CREATE INDEX IF NOT EXISTS idx_agendamentos_cliente ON agendamentos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_agendamentos_servico ON agendamentos(servico_id);
CREATE INDEX IF NOT EXISTS idx_agendamentos_expiracao ON agendamentos(expira_em) WHERE status = 'RESERVA_TEMPORARIA';

-- Tokens do link de acesso do cliente: guarda-se apenas o hash SHA-256.
CREATE TABLE IF NOT EXISTS tokens_acesso (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id  BIGINT NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
  token_hash  CHAR(64) NOT NULL UNIQUE,
  criado_em   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expira_em   TIMESTAMP NOT NULL,
  usado_em    TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_tokens_cliente ON tokens_acesso(cliente_id, criado_em);

-- Contas administrativas individuais. Sem senha padrão: a conta inicial do proprietário
-- é criada na partida da aplicação a partir de variáveis de ambiente (docs/seguranca.md).
CREATE TABLE IF NOT EXISTS usuarios_admin (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username       VARCHAR(60) NOT NULL UNIQUE,
  nome           VARCHAR(100) NOT NULL,
  senha_hash     VARCHAR(100) NOT NULL,
  papel          VARCHAR(12) NOT NULL CHECK (papel IN ('PROPRIETARIO','TECNICO')),
  ativo          BOOLEAN NOT NULL DEFAULT TRUE,
  falhas_login   INTEGER NOT NULL DEFAULT 0,
  bloqueado_ate  TIMESTAMP,
  ultimo_login_em TIMESTAMP,
  criado_em      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMIT;
